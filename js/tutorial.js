export const TRACKS = { shiner: SHINER, owner: OWNER, law: LAW };
export const trackOf = role => TRACKS[role] || SHINER;

// Текущий шаг = первый невыполненный. Если всё сделано — обучение закончено.
export function currentStep(state) {
  const track = trackOf(state.role);
  const done = track.filter(st => { try { return st.check(state); } catch { return false; } }).length;
  const step = track.find(st => { try { return !st.check(state); } catch { return true; } }) || null;
  return { step, done, total: track.length, finished: !step };
}
export function progress(state) { const { done, total } = currentStep(state); return { done, total }; }
